//go:build ignore

// Command faultgen writes fault_gen_test.go: the repositories of FaultStore
// (fault_test.go). Each repository embeds the one it wraps and overrides
// every method that returns an error, so FaultStore can fail any call by its
// name ("Lessons.Lock"). Run it with go generate after changing the
// interfaces in internal/store/store.go.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"slices"
	"strings"
)

const (
	source = "../store/store.go"
	target = "fault_gen_test.go"
)

func main() {
	fset := token.NewFileSet()

	file, err := parser.ParseFile(fset, source, nil, parser.SkipObjectResolution)
	if err != nil {
		log.Fatal(err)
	}

	g := &generator{interfaces: map[string]*ast.InterfaceType{}, imports: map[string]string{}, used: map[string]bool{}}
	g.collect(file)

	out, err := g.generate()
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(target, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

type generator struct {
	interfaces map[string]*ast.InterfaceType
	types      []string          // every type the store package declares
	imports    map[string]string // package name -> import path
	used       map[string]bool   // package names the output refers to
}

func (g *generator) collect(file *ast.File) {
	for _, imp := range file.Imports {
		path := strings.Trim(imp.Path.Value, `"`)
		g.imports[path[strings.LastIndex(path, "/")+1:]] = path
	}

	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}

		for _, spec := range gen.Specs {
			ts := spec.(*ast.TypeSpec)
			g.types = append(g.types, ts.Name.Name)

			if it, ok := ts.Type.(*ast.InterfaceType); ok {
				g.interfaces[ts.Name.Name] = it
			}
		}
	}
}

// repo is a repository the transaction hands out.
type repo struct {
	accessor string // the Tx method, e.g. Lessons
	iface    string // its interface, e.g. LessonRepo
}

func (g *generator) generate() ([]byte, error) {
	var repos []repo

	for _, m := range g.interfaces["Tx"].Methods.List {
		ft, ok := m.Type.(*ast.FuncType)
		if !ok || len(m.Names) != 1 || ft.Params.NumFields() != 0 || ft.Results.NumFields() != 1 {
			continue
		}

		id, ok := ft.Results.List[0].Type.(*ast.Ident)
		if !ok || g.interfaces[id.Name] == nil {
			continue
		}

		repos = append(repos, repo{accessor: m.Names[0].Name, iface: id.Name})
	}

	var body bytes.Buffer

	body.WriteString("// faultTx hands out the wrapped repositories of a FaultStore.\n")
	body.WriteString("type faultTx struct {\n\tstore.Tx\n\tf *FaultStore\n}\n\n")

	for _, r := range repos {
		fmt.Fprintf(&body, "func (t *faultTx) %s() store.%s {\n\treturn &fault%s{%s: t.Tx.%s(), f: t.f}\n}\n\n",
			r.accessor, r.iface, r.iface, r.iface, r.accessor)
	}

	for _, r := range repos {
		g.writeRepo(&body, r)
	}

	g.used["store"] = true

	var paths []string

	for name := range g.used {
		path, ok := g.imports[name]
		if name == "store" {
			path, ok = "github.com/cwbudde/studio-schedule/internal/store", true
		}

		if !ok {
			return nil, fmt.Errorf("unknown package %s", name)
		}

		paths = append(paths, path)
	}

	slices.Sort(paths)

	var out bytes.Buffer

	out.WriteString("// Code generated by faultgen.go; DO NOT EDIT.\n\npackage service\n\nimport (\n")

	for _, p := range paths { // the standard library first, as goimports groups them
		if !strings.Contains(p, ".") {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}

	out.WriteString("\n")

	for _, p := range paths {
		if strings.Contains(p, ".") {
			fmt.Fprintf(&out, "\t%q\n", p)
		}
	}

	out.WriteString(")\n\n")
	out.Write(body.Bytes())

	return format.Source(out.Bytes())
}

func (g *generator) writeRepo(w *bytes.Buffer, r repo) {
	fmt.Fprintf(w, "type fault%s struct {\n\tstore.%s\n\tf *FaultStore\n}\n\n", r.iface, r.iface)

	for _, m := range g.interfaces[r.iface].Methods.List {
		ft, ok := m.Type.(*ast.FuncType)
		if !ok || ft.Results == nil {
			continue
		}

		last := ft.Results.List[len(ft.Results.List)-1]
		if id, ok := last.Type.(*ast.Ident); !ok || id.Name != "error" {
			continue // cannot fail: the embedded repository answers
		}

		var params, args, results, zeros []string

		for _, p := range ft.Params.List {
			for range max(len(p.Names), 1) {
				name := fmt.Sprintf("a%d", len(args))

				arg := name
				if _, ok := p.Type.(*ast.Ellipsis); ok {
					arg += "..."
				}

				params = append(params, name+" "+g.typeString(p.Type))
				args = append(args, arg)
			}
		}

		for _, res := range ft.Results.List {
			for range max(len(res.Names), 1) {
				typ := g.typeString(res.Type)
				if typ == "error" {
					results = append(results, "err error")

					continue
				}

				name := fmt.Sprintf("r%d", len(zeros))
				results = append(results, name+" "+typ)
				zeros = append(zeros, name)
			}
		}

		method := m.Names[0].Name
		fmt.Fprintf(w, "func (r *fault%s) %s(%s) (%s) {\n", r.iface, method,
			strings.Join(params, ", "), strings.Join(results, ", "))
		fmt.Fprintf(w, "\tif err = r.f.hit(%q); err != nil {\n\t\treturn %s\n\t}\n\n",
			r.accessor+"."+method, strings.Join(append(zeros, "err"), ", "))
		fmt.Fprintf(w, "\treturn r.%s.%s(%s)\n}\n\n", r.iface, method, strings.Join(args, ", "))
	}
}

// typeString writes a type of store.go as seen from package service.
func (g *generator) typeString(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		if slices.Contains(g.types, e.Name) {
			g.used["store"] = true

			return "store." + e.Name
		}

		return e.Name
	case *ast.SelectorExpr:
		pkg := e.X.(*ast.Ident).Name
		g.used[pkg] = true

		return pkg + "." + e.Sel.Name
	case *ast.StarExpr:
		return "*" + g.typeString(e.X)
	case *ast.ArrayType:
		if e.Len != nil {
			return "[" + e.Len.(*ast.BasicLit).Value + "]" + g.typeString(e.Elt)
		}

		return "[]" + g.typeString(e.Elt)
	case *ast.Ellipsis:
		return "..." + g.typeString(e.Elt)
	case *ast.MapType:
		return "map[" + g.typeString(e.Key) + "]" + g.typeString(e.Value)
	case *ast.FuncType:
		var params, results []string

		for _, p := range e.Params.List {
			for range max(len(p.Names), 1) {
				params = append(params, g.typeString(p.Type))
			}
		}

		if e.Results != nil {
			for _, r := range e.Results.List {
				for range max(len(r.Names), 1) {
					results = append(results, g.typeString(r.Type))
				}
			}
		}

		return "func(" + strings.Join(params, ", ") + ") (" + strings.Join(results, ", ") + ")"
	default:
		log.Fatalf("faultgen: unsupported type %T", e)

		return ""
	}
}
